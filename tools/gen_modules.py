def keep_value(e):
    return -9999 if e["kind"] == "SLIDER" and e["lo"] < 0 else -1


def setting_attr(name):
    e = SETTINGS[name]
    title = f'"$STR_root_ads_main_{name}"'
    tip = f'"$STR_root_ads_main_{name}_desc"'
    cls = f"ROOT_ADS_S_{name}"
    if e["kind"] == "CHECKBOX":
        return f"ATTR_TRI_RAW({cls},{title},{tip});"
    if e["kind"] == "SLIDER":
        return f"ATTR_NUM_RAW({cls},{title},{tip},{keep_value(e)});"
    if e["kind"] == "LIST":
        lines = [f"class {cls}: Combo {{",
                 f'    property = "{cls}";',
                 f"    displayName = {title};",
                 f"    tooltip = {tip};",
                 '    typeName = "NUMBER";',
                 "    defaultValue = -1;",
                 "    class Values {",
                 '        class Keep { name = CSTRING(keepSetting); value = -1; };']
        for i, v in enumerate(e["values"]):
            lines.append(f'        class V{i} {{ name = "$STR_root_ads_main_{name}_opt{i}"; value = {v}; }};')
        lines += ["    };", "};"]
        return "\n".join(lines)
    raise ValueError(name)


def indent(text, n):
    pad = " " * n
    return "\n".join(pad + l if l else l for l in text.split("\n"))


