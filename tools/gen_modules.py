def eden(cls, fnc, name, trigger, attrs, desc, extra=""):
    return dict(cls=cls, fnc=fnc, name=s(f"eden_{cls}", name), trigger=trigger, attrs=attrs, desc=s(f"eden_{cls}_desc", desc), extra=extra)


def a_num(cls, label, tip, default):
    return f"ATTR_NUM({cls},{s(cls, label)},{s(cls + '_desc', tip)},{default});"


def a_str(cls, label, tip, default):
    return f'ATTR_STR({cls},{s(cls, label)},{s(cls + "_desc", tip)},"""{default}""");'


def a_bool(cls, label, tip, default):
    return f"ATTR_BOOL({cls},{s(cls, label)},{s(cls + '_desc', tip)},{'true' if default else 'false'});"


def a_tri(cls, label, tip):
    return f"ATTR_TRI({cls},{s(cls, label)},{s(cls + '_desc', tip)});"


def a_combo(cls, label, tip, type_name, default, options):
    lines = [f"class {cls}: Combo {{", f'    property = "{cls}";', f"    displayName = {s(cls, label)};",
             f"    tooltip = {s(cls + '_desc', tip)};", f'    typeName = "{type_name}";',
             f"    defaultValue = {default};", "    class Values {"]
    for i, (value, text) in enumerate(options):
        key = f"{cls}_v{i}"
        v = f'"{value}"' if type_name == "STRING" else value
        lines.append(f"        class V{i} {{ name = {s(key, text)}; value = {v}; }};")
    lines += ["    };", "};"]
    return "\n".join(lines)


